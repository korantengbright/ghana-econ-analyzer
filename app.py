# --- DATA ENGINES (WITH CACHING) ---

@st.cache_data(ttl=3600)
def fetch_live_macro_data():
    """Fetches inflation from BoG and live USD/GHS rate."""
    # 1. Real-time Exchange Rate (March 2026 Live)
    try:
        fx_url = "https://api.frankfurter.dev/v1/latest?base=USD&symbols=GHS"
        fx_data = requests.get(fx_url).json()
        usd_ghs = fx_data['rates']['GHS']
    except:
        usd_ghs = 10.84 # Fallback for March 2026
        
    # 2. Latest Inflation (March 2026 logic)
    # In a full app, you'd use the PDF scraper here. For this demo, we use the latest verified print.
    inflation = 3.3  # February/March 2026 official rate
    
    return usd_ghs, inflation

@st.cache_data
def generate_pdf_bytes(amount, interest, inflation, real_rate, usd_val):
    pdf = FPDF()
    pdf.add_page()
    pdf.set_font("Helvetica", "B", 16)
    pdf.cell(0, 10, "Ghana Financial Analysis Report", ln=True, align='C')
    pdf.set_font("Helvetica", size=12)
    pdf.ln(10)
    pdf.cell(0, 10, f"Date: {datetime.now().strftime('%Y-%m-%d')}", ln=True)
    pdf.cell(0, 10, f"Principal Amount: {amount:,.2f} GHS", ln=True)
    pdf.cell(0, 10, f"Nominal Interest Rate: {interest}%", ln=True)
    pdf.cell(0, 10, f"National Inflation Rate: {inflation}%", ln=True)
    pdf.cell(0, 10, f"Calculated Real Return: {real_rate:.2f}%", ln=True)
    pdf.cell(0, 10, f"USD Portfolio Value: ${usd_val:,.2f}", ln=True)
    pdf.ln(20)
    pdf.set_font("Helvetica", "I", 8)
    pdf.multi_cell(0, 5, "Generated by Ghana Econ-Insight Tool. Data sourced from BoG and Frankfurter API.")
    return bytes(pdf.output())

# --- MAIN APP LOGIC ---

# Sidebar
st.sidebar.header("📊 Investment Settings")
amount = st.sidebar.number_input("Investment Amount (GHS)", min_value=100, value=10000, step=100)
nominal_rate = st.sidebar.slider("Nominal Annual Rate (%)", 0.0, 40.0, 15.5) # 15.5% is BoG Policy Rate Mar '26

# Fetch Data
usd_ghs, inflation_rate = fetch_live_macro_data()

# Calculations
real_return = (((1 + (nominal_rate/100)) / (1 + (inflation_rate/100))) - 1) * 100
usd_equiv = amount / usd_ghs

# Header
st.title("🇬🇭 Ghana Strategic Financial Dashboard")
st.write(f"Refined economic analysis for the Ghanaian market. Current Date: **{datetime.now().strftime('%B %d, %Y')}**")

# Top Metrics
m1, m2, m3 = st.columns(3)
m1.metric("USD / GHS Rate", f"{usd_ghs:.2f}", "-0.05", help="Live Interbank Rate")
m2.metric("Inflation (YoY)", f"{inflation_rate}%", "-0.5%", help="Source: Ghana Statistical Service")
m3.metric("Your Real Return", f"{real_return:.2f}%", delta_color="normal")

# Analysis Section
st.divider()
c1, c2 = st.columns([2, 1])

with c1:
    st.subheader("12-Month Projection")
    months = list(range(0, 13))
    values = [amount * (1 + (nominal_rate/100/12))**m for m in months]
    df_plot = pd.DataFrame({"Month": months, "GHS Value": values})
    fig = px.area(df_plot, x="Month", y="GHS Value", color_discrete_sequence=['#006b3f'])
    st.plotly_chart(fig, use_container_width=True)

with c2:
    st.subheader("Summary")
    st.write(f"At a nominal rate of **{nominal_rate}%**, your wealth is growing at **{real_return:.2f}%** after accounting for inflation.")
    if real_return < 5:
        st.warning("Your real growth is low. Consider higher-yield assets.")
    else:
        st.success("You are successfully beating inflation!")
        
    # PDF Download
    pdf_data = generate_pdf_bytes(amount, nominal_rate, inflation_rate, real_return, usd_equiv)
    st.download_button(
        label="📥 Download Professional Report",
        data=pdf_data,
        file_name=f"Ghana_Econ_Report_{datetime.now().strftime('%Y%m%d')}.pdf",
        mime="application/pdf"
    )

st.divider()
st.caption("Built for Economic Analysis & Statistics Research - Accra, 2026")
